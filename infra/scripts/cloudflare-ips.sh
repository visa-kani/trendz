#!/usr/bin/env bash
# Regenerates /etc/nginx/conf.d/cloudflare-real-ip.conf so Nginx (and therefore
# the API's rate limits and audit logs) see the visitor's IP, not Cloudflare's.
# Run as root after provisioning and monthly from cron. If the site is NOT
# proxied through Cloudflare, run with --none to write an empty file instead.
set -Eeuo pipefail

OUT=/etc/nginx/conf.d/cloudflare-real-ip.conf
TMP="$(mktemp)"

if [[ "${1:-}" == "--none" ]]; then
  echo "# Cloudflare proxy not in use" > "$TMP"
else
  {
    echo "# Generated by cloudflare-ips.sh on $(date -u +%F)"
    for list in ips-v4 ips-v6; do
      curl -fsS "https://www.cloudflare.com/$list" | while read -r cidr; do
        [[ -n "$cidr" ]] && echo "set_real_ip_from $cidr;"
      done
    done
    echo "real_ip_header CF-Connecting-IP;"
  } > "$TMP"
  grep -q set_real_ip_from "$TMP" || { echo "could not download Cloudflare ranges" >&2; exit 1; }
fi

install -m 644 "$TMP" "$OUT"
rm -f "$TMP"
nginx -t && systemctl reload nginx
echo "updated $OUT"
